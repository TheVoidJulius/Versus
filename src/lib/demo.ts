import type { ModelOption } from "@/data/models";

export function makeDemoResponse(prompt: string, model: ModelOption): string {
  const cleanPrompt = prompt.trim();
  const angle = model.provider === "groq"
    ? [
        "I’d start by making the goal and constraints explicit.",
        "Then I’d work through a small example before generalizing.",
        "Finally, I’d check the result against the original request.",
      ]
    : [
        "First, identify the outcome that would make this useful.",
        "Next, break the work into a few concrete steps.",
        "Before finishing, test the result against the stated goal.",
      ];

  return [
    `Sample response for: “${cleanPrompt.slice(0, 180)}${cleanPrompt.length > 180 ? "…" : ""}”`,
    "",
    ...angle.map((step, index) => `${index + 1}. ${step}`),
    "",
    "This is a local preview sample, not a response generated by an AI model. Add the matching provider API key to enable live inference.",
  ].join("\n");
}
